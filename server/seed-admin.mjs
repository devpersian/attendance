import bcrypt from 'bcryptjs';
import { execute, executeInsert, getPool } from './db.mjs';
import { Logger } from './services/logger.mjs';

async function seedAdmin() {
  try {
    await getPool();
    console.log('🔐 Seeding admin user...');

    // Check if admin user already exists
    const existingAdmin = await execute(
      'SELECT Id FROM attendance.Users WHERE Username = @username',
      { username: 'admin' }
    );

    if (existingAdmin.length > 0) {
      console.log('⚠️  Admin user already exists. Updating password and role...');
      
      // Update the password and ensure role is 'admin' for existing admin user
      const password = 'admin123';
      const saltRounds = 10;
      const passwordHash = await bcrypt.hash(password, saltRounds);
      
      await execute(
        'UPDATE attendance.Users SET PasswordHash = @passwordHash, Role = @role, IsActive = 1, UpdatedAt = GETDATE() WHERE Username = @username',
        { passwordHash, username: 'admin', role: 'admin' }
      );
      
      console.log('✅ Admin password and role updated successfully!');
      console.log('   Username: admin');
      console.log('   Password: admin123');
      console.log('   Role: admin');
      console.log('   ⚠️  Please change the password after first login!');
      
      await Logger.log('success', 'SEED', 'admin', existingAdmin[0].Id, 'Admin password and role updated', { username: 'admin' });
      
      process.exit(0);
    }

    // Hash the default password
    const password = 'admin123';
    const saltRounds = 10;
    const passwordHash = await bcrypt.hash(password, saltRounds);

    // Create admin user (Id is INT IDENTITY — generated by the database)
    const adminId = await executeInsert(`INSERT INTO attendance.Users (Username, PasswordHash, Email, Role, IsActive, CreatedAt)
       VALUES (@username, @passwordHash, @email, @role, 1, GETDATE())`, { username: 'admin', passwordHash, email: 'admin@company.com', role: 'admin' });

    console.log('✅ Admin user created successfully!');
    console.log('   Username: admin');
    console.log('   Password: admin123');
    console.log('   ⚠️  Please change the password after first login!');

    await Logger.log('success', 'SEED', 'admin', adminId, 'Admin user seeded', { username: 'admin' });

    process.exit(0);
  } catch (error) {
    console.error('❌ Error seeding admin user:', error);
    await Logger.logError('SEED', 'admin', null, 'Admin seed error', error);
    process.exit(1);
  }
}

seedAdmin();
