import express from 'express';
import { execute, executeInsert } from '../db.mjs';
import { Logger } from '../services/logger.mjs';

import { authenticateToken } from '../services/auth.mjs';

const router = express.Router();

// Phase 0 (route-auth enforcement): every endpoint on this router
// requires a valid session token. Public auth endpoints live only under /api/auth.
router.use(authenticateToken);

// GET /api/shift-patterns - Get all shift patterns
router.get('/', async (req, res) => {
  try {
    const patterns = await execute(`
      SELECT sp.*, 
             (SELECT COUNT(*) FROM attendance.ShiftPatternPeriods spp WHERE spp.PatternId = sp.Id) as PeriodCount
      FROM attendance.ShiftPatterns sp
      WHERE sp.IsActive = 1
      ORDER BY sp.Name
    `);
    
    await Logger.info('READ', 'shift_patterns', null, `Fetched ${patterns.length} patterns`);
    res.json(patterns);
  } catch (error) {
    await Logger.error('READ', 'shift_patterns', null, 'Failed to fetch patterns', { error: error.message });
    res.status(500).json({ error: 'Failed to fetch patterns' });
  }
});

// GET /api/shift-patterns/:id - Get pattern by ID with periods
router.get('/:id', async (req, res) => {
  try {
    const { id } = req.params;
    
    const patterns = await execute('SELECT * FROM attendance.ShiftPatterns WHERE Id = @id', { id });
    
    if (patterns.length === 0) {
      return res.status(404).json({ error: 'Pattern not found' });
    }
    
    const periods = await execute(`
      SELECT spp.*, s.Name as ShiftName
      FROM attendance.ShiftPatternPeriods spp
      LEFT JOIN attendance.Shifts s ON spp.ShiftId = s.Id
      WHERE spp.PatternId = @id
      ORDER BY spp.PeriodOrder
    `, { id });
    
    res.json({ ...patterns[0], periods });
  } catch (error) {
    await Logger.error('READ', 'shift_pattern', req.params.id, 'Failed to fetch pattern', { error: error.message });
    res.status(500).json({ error: 'Failed to fetch pattern' });
  }
});

// POST /api/shift-patterns - Create new pattern
router.post('/', async (req, res) => {
  try {
    const { name, description, totalCycleHours, periods } = req.body;
    
    // Validate input
    if (!name || !totalCycleHours || totalCycleHours <= 0) {
      return res.status(400).json({ error: 'Invalid input: name and totalCycleHours are required' });
    }
    
    // Create pattern (Id is INT IDENTITY — generated by the database)
    const id = await executeInsert(`INSERT INTO attendance.ShiftPatterns (Name, Description, TotalCycleHours)
       VALUES (@name, @description, @totalCycleHours)`, { name, description: description || null, totalCycleHours });
    
    // Create periods if provided
    if (periods && Array.isArray(periods)) {
      for (const period of periods) {
        await executeInsert(`INSERT INTO attendance.ShiftPatternPeriods (PatternId, PeriodOrder, PeriodType, DurationHours, ShiftId, Description)
           VALUES (@patternId, @order, @type, @duration, @shiftId, @description)`, { patternId: id, order: period.periodOrder, type: period.periodType, duration: period.durationHours, shiftId: period.shiftId || null, description: period.description || null });
      }
    }
    
    await Logger.success('CREATE', 'shift_pattern', id, `Pattern created: ${name}`, { name, totalCycleHours });
    res.status(201).json({ message: 'Pattern created successfully', id });
  } catch (error) {
    await Logger.error('CREATE', 'shift_pattern', null, 'Failed to create pattern', { error: error.message, body: req.body });
    res.status(500).json({ error: 'Failed to create pattern' });
  }
});

// PUT /api/shift-patterns/:id - Update pattern
router.put('/:id', async (req, res) => {
  try {
    const { id } = req.params;
    const { name, description, totalCycleHours, isActive } = req.body;
    
    const updates = [];
    const params = { id };
    
    if (name !== undefined) {
      updates.push('Name = @name');
      params.name = name;
    }
    
    if (description !== undefined) {
      updates.push('Description = @description');
      params.description = description;
    }
    
    if (totalCycleHours !== undefined) {
      updates.push('TotalCycleHours = @totalCycleHours');
      params.totalCycleHours = totalCycleHours;
    }
    
    if (isActive !== undefined) {
      updates.push('IsActive = @isActive');
      params.isActive = isActive;
    }
    
    if (updates.length === 0) {
      return res.json({ message: 'No changes to update' });
    }
    
    updates.push('UpdatedAt = GETDATE()');
    
    await execute(
      `UPDATE attendance.ShiftPatterns SET ${updates.join(', ')} WHERE Id = @id`,
      params
    );
    
    await Logger.success('UPDATE', 'shift_pattern', id, 'Pattern updated', { name, totalCycleHours });
    res.json({ message: 'Pattern updated successfully' });
  } catch (error) {
    await Logger.error('UPDATE', 'shift_pattern', req.params.id, 'Failed to update pattern', { error: error.message, body: req.body });
    res.status(500).json({ error: 'Failed to update pattern' });
  }
});

// DELETE /api/shift-patterns/:id - Delete pattern
router.delete('/:id', async (req, res) => {
  try {
    const { id } = req.params;
    
    // Check if pattern is assigned to any employees
    const assignments = await execute(
      'SELECT COUNT(*) as count FROM attendance.EmployeeShifts WHERE PatternId = @id',
      { id }
    );
    
    if (assignments[0].count > 0) {
      return res.status(400).json({ 
        error: 'Cannot delete pattern: it is assigned to employees',
        assignmentCount: assignments[0].count
      });
    }
    
    await execute('DELETE FROM attendance.ShiftPatterns WHERE Id = @id', { id });
    
    await Logger.success('DELETE', 'shift_pattern', id, 'Pattern deleted');
    res.json({ message: 'Pattern deleted successfully' });
  } catch (error) {
    await Logger.error('DELETE', 'shift_pattern', req.params.id, 'Failed to delete pattern', { error: error.message });
    res.status(500).json({ error: 'Failed to delete pattern' });
  }
});

// GET /api/shift-patterns/:id/calculate - Calculate current period for an employee
router.get('/:id/calculate', async (req, res) => {
  try {
    const { id } = req.params;
    const { startDate, currentDate } = req.query;
    
    if (!startDate || !currentDate) {
      return res.status(400).json({ error: 'startDate and currentDate are required' });
    }
    
    // Get pattern
    const patterns = await execute('SELECT * FROM attendance.ShiftPatterns WHERE Id = @id', { id });
    if (patterns.length === 0) {
      return res.status(404).json({ error: 'Pattern not found' });
    }
    
    const pattern = patterns[0];
    
    // Get periods
    const periods = await execute(`
      SELECT * FROM attendance.ShiftPatternPeriods
      WHERE PatternId = @id
      ORDER BY PeriodOrder
    `, { id });
    
    // Calculate elapsed hours
    const start = new Date(startDate);
    const current = new Date(currentDate);
    const elapsedMs = current - start;
    const elapsedHours = elapsedMs / (1000 * 60 * 60);
    
    // Calculate cycle position
    const cyclePosition = elapsedHours % pattern.TotalCycleHours;
    
    // Find current period
    let accumulatedHours = 0;
    let currentPeriod = null;
    let periodStartHours = 0;
    
    for (const period of periods) {
      if (cyclePosition >= accumulatedHours && cyclePosition < accumulatedHours + period.DurationHours) {
        currentPeriod = period;
        periodStartHours = accumulatedHours;
        break;
      }
      accumulatedHours += period.DurationHours;
    }
    
    // If no period found (shouldn't happen), use the last period
    if (!currentPeriod && periods.length > 0) {
      currentPeriod = periods[periods.length - 1];
      periodStartHours = pattern.TotalCycleHours - currentPeriod.DurationHours;
    }
    
    // Calculate hours into current period and hours remaining
    const hoursIntoPeriod = cyclePosition - periodStartHours;
    const hoursRemainingInPeriod = currentPeriod ? currentPeriod.DurationHours - hoursIntoPeriod : 0;
    
    // Calculate next period
    const nextPeriodIndex = periods.findIndex(p => p.Id === currentPeriod?.Id) + 1;
    const nextPeriod = nextPeriodIndex < periods.length ? periods[nextPeriodIndex] : periods[0];
    
    res.json({
      pattern,
      currentPeriod,
      hoursIntoPeriod: Math.round(hoursIntoPeriod * 100) / 100,
      hoursRemainingInPeriod: Math.round(hoursRemainingInPeriod * 100) / 100,
      nextPeriod,
      cyclePosition: Math.round(cyclePosition * 100) / 100,
      totalCycleHours: pattern.TotalCycleHours
    });
  } catch (error) {
    await Logger.error('CALCULATE', 'shift_pattern', req.params.id, 'Failed to calculate period', { error: error.message });
    res.status(500).json({ error: 'Failed to calculate period' });
  }
});

export default router;
