import express from 'express';
import { execute, executeInsert } from '../db.mjs';
import { Logger } from '../services/logger.mjs';
import { authenticateToken, requireRole } from '../services/auth.mjs';
import { writeAudit } from '../services/auditLog.mjs';
import { getAllPermissions, getEffectivePermissionIds, rowsToTree, minimizeSelection } from '../services/permissionTree.mjs';

const router = express.Router();

// All routes require authentication and admin role
router.use(authenticateToken);
router.use(requireRole('admin'));

// GET /api/roles - Get all roles
router.get('/', async (req, res) => {
  const startTime = Date.now();
  
  try {
    const roles = await execute(
      `SELECT r.*, p.Name AS ParentName,
              (SELECT COUNT(*) FROM attendance.UserRoles ur WHERE ur.RoleId = r.Id) as UserCount,
              (SELECT COUNT(*) FROM attendance.RolePermissions rp WHERE rp.RoleId = r.Id) as PermissionCount
       FROM attendance.Roles r
       LEFT JOIN attendance.Roles p ON r.ParentId = p.Id
       WHERE r.Name NOT LIKE 'user:%'
       ORDER BY ISNULL(r.SortOrder, 0), r.CreatedAt DESC`
    );

    await Logger.logRequest('GET', '/api/roles', 200, Date.now() - startTime, req.user.id);
    res.json({ roles, tree: rowsToTree(roles) });
  } catch (error) {
    await Logger.logError('ROLES', 'get_all', null, 'Get roles error', error, { userId: req.user.id });
    await Logger.logRequest('GET', '/api/roles', 500, Date.now() - startTime, req.user.id, { error: error.message });
    res.status(500).json({ error: 'خطا در دریافت نقش‌ها' });
  }
});

// GET /api/roles/:id - Get role by ID
router.get('/:id', async (req, res) => {
  const startTime = Date.now();
  
  try {
    const roles = await execute(
      'SELECT * FROM attendance.Roles WHERE Id = @id',
      { id: req.params.id }
    );

    if (roles.length === 0) {
      await Logger.logRequest('GET', `/api/roles/${req.params.id}`, 404, Date.now() - startTime, req.user.id, { reason: 'Role not found' });
      return res.status(404).json({ error: 'نقش یافت نشد' });
    }

    // Get permissions for this role
    const permissions = await execute(
      `SELECT p.* 
       FROM attendance.RolePermissions rp
       INNER JOIN attendance.Permissions p ON rp.PermissionId = p.Id
       WHERE rp.RoleId = @roleId`,
      { roleId: req.params.id }
    );

    await Logger.logRequest('GET', `/api/roles/${req.params.id}`, 200, Date.now() - startTime, req.user.id);
    res.json({ ...roles[0], permissions });
  } catch (error) {
    await Logger.logError('ROLES', 'get_one', req.params.id, 'Get role error', error, { userId: req.user.id });
    await Logger.logRequest('GET', `/api/roles/${req.params.id}`, 500, Date.now() - startTime, req.user.id, { error: error.message });
    res.status(500).json({ error: 'خطا در دریافت نقش' });
  }
});

// POST /api/roles - Create new role
router.post('/', async (req, res) => {
  const startTime = Date.now();
  
  try {
    const { name, description, parentId, sortOrder } = req.body;

    if (!name) {
      await Logger.logRequest('POST', '/api/roles', 400, Date.now() - startTime, req.user.id, { reason: 'Missing name' });
      return res.status(400).json({ error: 'نام نقش الزامی است' });
    }

    // Check if role name already exists
    const existing = await execute(
      'SELECT Id FROM attendance.Roles WHERE Name = @name',
      { name }
    );

    if (existing.length > 0) {
      await Logger.log('warning', 'ROLE_CREATE_FAILED', 'roles', null, `Role name already exists: ${name}`, { name });
      await Logger.logRequest('POST', '/api/roles', 400, Date.now() - startTime, req.user.id, { reason: 'Name exists' });
      return res.status(400).json({ error: 'این نام نقش قبلاً ثبت شده است' });
    }

    // Validate parent exists when provided (role tree)
    if (parentId) {
      const parent = await execute('SELECT Id FROM attendance.Roles WHERE Id = @id', { id: parentId });
      if (parent.length === 0) {
        await Logger.logRequest('POST', '/api/roles', 400, Date.now() - startTime, req.user.id, { reason: 'Parent role not found' });
        return res.status(400).json({ error: 'نقش والد یافت نشد' });
      }
    }

    // Id is INT IDENTITY — generated by the database
    const roleId = await executeInsert(`INSERT INTO attendance.Roles (Name, Description, ParentId, SortOrder, IsSystem, CreatedAt, UpdatedAt)
       VALUES (@name, @description, @parentId, @sortOrder, 0, GETDATE(), GETDATE())`,
      { name, description: description || null, parentId: parentId || null, sortOrder: sortOrder ?? 0 });

    await Logger.log('success', 'ROLE_CREATED', 'roles', roleId, `Role created: ${name}`, { name, description }, req.user.id);
    await Logger.logRequest('POST', '/api/roles', 201, Date.now() - startTime, req.user.id);

    await writeAudit({ actorUserId: req.user?.id ?? null, action: 'ROLE_CREATED', entity: 'role', entityId: req.params?.id ?? null, req });

    res.status(201).json({
      message: 'نقش با موفقیت ایجاد شد',
      role: { id: roleId, name, description },
    });
  } catch (error) {
    await Logger.logError('ROLES', 'create', null, 'Create role error', error, { body: req.body, userId: req.user.id });
    await Logger.logRequest('POST', '/api/roles', 500, Date.now() - startTime, req.user.id, { error: error.message });
    res.status(500).json({ error: 'خطا در ایجاد نقش' });
  }
});

// PUT /api/roles/:id - Update role
router.put('/:id', async (req, res) => {
  const startTime = Date.now();
  
  try {
    const { name, description, parentId, sortOrder } = req.body;

    // Check if role exists
    const roles = await execute(
      'SELECT * FROM attendance.Roles WHERE Id = @id',
      { id: req.params.id }
    );

    if (roles.length === 0) {
      await Logger.logRequest('PUT', `/api/roles/${req.params.id}`, 404, Date.now() - startTime, req.user.id, { reason: 'Role not found' });
      return res.status(404).json({ error: 'نقش یافت نشد' });
    }

    // Check if system role
    if (roles[0].IsSystem) {
      await Logger.log('warning', 'ROLE_UPDATE_DENIED', 'roles', req.params.id, 'Attempted to update system role', { roleId: req.params.id });
      await Logger.logRequest('PUT', `/api/roles/${req.params.id}`, 403, Date.now() - startTime, req.user.id, { reason: 'System role' });
      return res.status(403).json({ error: 'نقش‌های سیستمی قابل ویرایش نیستند' });
    }

    // Reparenting guard: parent must exist and cannot be the role itself or one of its descendants
    let newParentId = parentId !== undefined ? (parentId || null) : roles[0].ParentId ?? null;
    if (newParentId) {
      const parent = await execute('SELECT Id FROM attendance.Roles WHERE Id = @id', { id: newParentId });
      if (parent.length === 0) {
        await Logger.logRequest('PUT', `/api/roles/${req.params.id}`, 400, Date.now() - startTime, req.user.id, { reason: 'Parent role not found' });
        return res.status(400).json({ error: 'نقش والد یافت نشد' });
      }
      const descendants = await getRoleDescendants(Number(req.params.id));
      if (descendants.includes(Number(newParentId))) {
        await Logger.logRequest('PUT', `/api/roles/${req.params.id}`, 400, Date.now() - startTime, req.user.id, { reason: 'Cycle' });
        return res.status(400).json({ error: 'نمی‌توان نقش را زیر یکی از فرزندان خود قرار داد' });
      }
    }

    await execute(
      `UPDATE attendance.Roles
       SET Name = @name, Description = @description, ParentId = @parentId,
           SortOrder = @sortOrder, UpdatedAt = GETDATE()
       WHERE Id = @id`,
      {
        id: req.params.id,
        name,
        description: description || null,
        parentId: newParentId,
        sortOrder: sortOrder ?? roles[0].SortOrder ?? 0,
      }
    );

    await Logger.log('success', 'ROLE_UPDATED', 'roles', req.params.id, `Role updated: ${name}`, { name, description }, req.user.id);
    await Logger.logRequest('PUT', `/api/roles/${req.params.id}`, 200, Date.now() - startTime, req.user.id);

    await writeAudit({ actorUserId: req.user?.id ?? null, action: 'ROLE_UPDATED', entity: 'role', entityId: req.params?.id ?? null, req });

    res.json({ message: 'نقش با موفقیت به‌روزرسانی شد' });
  } catch (error) {
    await Logger.logError('ROLES', 'update', req.params.id, 'Update role error', error, { body: req.body, userId: req.user.id });
    await Logger.logRequest('PUT', `/api/roles/${req.params.id}`, 500, Date.now() - startTime, req.user.id, { error: error.message });
    res.status(500).json({ error: 'خطا در به‌روزرسانی نقش' });
  }
});

// DELETE /api/roles/:id - Delete role
router.delete('/:id', async (req, res) => {
  const startTime = Date.now();
  
  try {
    // Check if role exists
    const roles = await execute(
      'SELECT * FROM attendance.Roles WHERE Id = @id',
      { id: req.params.id }
    );

    if (roles.length === 0) {
      await Logger.logRequest('DELETE', `/api/roles/${req.params.id}`, 404, Date.now() - startTime, req.user.id, { reason: 'Role not found' });
      return res.status(404).json({ error: 'نقش یافت نشد' });
    }

    // Check if system role
    if (roles[0].IsSystem) {
      await Logger.log('warning', 'ROLE_DELETE_DENIED', 'roles', req.params.id, 'Attempted to delete system role', { roleId: req.params.id });
      await Logger.logRequest('DELETE', `/api/roles/${req.params.id}`, 403, Date.now() - startTime, req.user.id, { reason: 'System role' });
      return res.status(403).json({ error: 'نقش‌های سیستمی قابل حذف نیستند' });
    }

    // Check if role has child roles in the tree
    const childRoles = await execute(
      'SELECT COUNT(*) as Count FROM attendance.Roles WHERE ParentId = @roleId',
      { roleId: req.params.id }
    );

    if (childRoles[0].Count > 0) {
      await Logger.log('warning', 'ROLE_DELETE_DENIED', 'roles', req.params.id, 'Role has child roles', { roleId: req.params.id });
      await Logger.logRequest('DELETE', `/api/roles/${req.params.id}`, 400, Date.now() - startTime, req.user.id, { reason: 'Has child roles' });
      return res.status(400).json({ error: 'این نقش دارای نقش فرزند است؛ ابتدا فرزندان را منتقل یا حذف کنید' });
    }

    // Check if role is assigned to users
    const userRoles = await execute(
      'SELECT COUNT(*) as Count FROM attendance.UserRoles WHERE RoleId = @roleId',
      { roleId: req.params.id }
    );

    if (userRoles[0].Count > 0) {
      await Logger.log('warning', 'ROLE_DELETE_DENIED', 'roles', req.params.id, 'Role has assigned users', { roleId: req.params.id, userCount: userRoles[0].Count });
      await Logger.logRequest('DELETE', `/api/roles/${req.params.id}`, 400, Date.now() - startTime, req.user.id, { reason: 'Has users' });
      return res.status(400).json({ error: 'این نقش به کاربران اختصاص داده شده است و قابل حذف نیست' });
    }

    await execute(
      'DELETE FROM attendance.Roles WHERE Id = @id',
      { id: req.params.id }
    );

    await Logger.log('success', 'ROLE_DELETED', 'roles', req.params.id, `Role deleted: ${roles[0].Name}`, { roleName: roles[0].Name }, req.user.id);
    await Logger.logRequest('DELETE', `/api/roles/${req.params.id}`, 200, Date.now() - startTime, req.user.id);

    await writeAudit({ actorUserId: req.user?.id ?? null, action: 'ROLE_DELETED', entity: 'role', entityId: req.params?.id ?? null, req });

    res.json({ message: 'نقش با موفقیت حذف شد' });
  } catch (error) {
    await Logger.logError('ROLES', 'delete', req.params.id, 'Delete role error', error, { userId: req.user.id });
    await Logger.logRequest('DELETE', `/api/roles/${req.params.id}`, 500, Date.now() - startTime, req.user.id, { error: error.message });
    res.status(500).json({ error: 'خطا در حذف نقش' });
  }
});

// PUT /api/roles/:id/permissions - Update role permissions
router.put('/:id/permissions', async (req, res) => {
  const startTime = Date.now();
  
  try {
    const { permissionIds } = req.body;

    if (!Array.isArray(permissionIds)) {
      await Logger.logRequest('PUT', `/api/roles/${req.params.id}/permissions`, 400, Date.now() - startTime, req.user.id, { reason: 'Invalid permissionIds' });
      return res.status(400).json({ error: 'لیست دسترسی‌ها نامعتبر است' });
    }

    // Check if role exists
    const roles = await execute(
      'SELECT * FROM attendance.Roles WHERE Id = @id',
      { id: req.params.id }
    );

    if (roles.length === 0) {
      await Logger.logRequest('PUT', `/api/roles/${req.params.id}/permissions`, 404, Date.now() - startTime, req.user.id, { reason: 'Role not found' });
      return res.status(404).json({ error: 'نقش یافت نشد' });
    }

    // Minimize selection: drop nodes already implied by a selected ancestor
    const allPerms = await getAllPermissions();
    const minimal = minimizeSelection(permissionIds, allPerms);

    // Delete existing permissions
    await execute(
      'DELETE FROM attendance.RolePermissions WHERE RoleId = @roleId',
      { roleId: req.params.id }
    );

    // Insert new permissions
    for (const permissionId of minimal) {
      await executeInsert(`INSERT INTO attendance.RolePermissions (RoleId, PermissionId, CreatedAt)
         VALUES (@roleId, @permissionId, GETDATE())`, { roleId: req.params.id, permissionId });
    }

    await Logger.log('success', 'ROLE_PERMISSIONS_UPDATED', 'roles', req.params.id, `Role permissions updated`, { permissionCount: minimal.length }, req.user.id);
    await Logger.logRequest('PUT', `/api/roles/${req.params.id}/permissions`, 200, Date.now() - startTime, req.user.id);

    await writeAudit({ actorUserId: req.user?.id ?? null, action: 'ROLE_PERMISSIONS_UPDATED', entity: 'role', entityId: req.params?.id ?? null, req });

    res.json({ message: 'دسترسی‌های نقش با موفقیت به‌روزرسانی شد' });
  } catch (error) {
    await Logger.logError('ROLES', 'update_permissions', req.params.id, 'Update permissions error', error, { body: req.body, userId: req.user.id });
    await Logger.logRequest('PUT', `/api/roles/${req.params.id}/permissions`, 500, Date.now() - startTime, req.user.id, { error: error.message });
    res.status(500).json({ error: 'خطا در به‌روزرسانی دسترسی‌ها' });
  }
});

// Descendant closure on the role tree (for cycle detection on reparenting)
async function getRoleDescendants(roleId) {
  if (!Number.isFinite(roleId)) return [];
  const rows = await execute(
    `WITH Descendants AS (
       SELECT Id FROM attendance.Roles WHERE ParentId = ${roleId}
       UNION ALL
       SELECT r.Id FROM attendance.Roles r
       INNER JOIN Descendants d ON r.ParentId = d.Id
     )
     SELECT Id FROM Descendants`
  );
  return rows.map(r => Number(r.Id));
}

