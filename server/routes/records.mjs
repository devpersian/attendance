import express from 'express';
import { execute, executeInsert } from '../db.mjs';
import { Logger } from '../services/logger.mjs';

import { authenticateToken } from '../services/auth.mjs';

const router = express.Router();

// All business endpoints require a valid session token.
router.use(authenticateToken);

// GET /api/records - Get all records (with optional filters)
router.get('/', async (req, res) => {
  try {
    const { date, employeeId, month, status } = req.query;
    let query = 'SELECT * FROM attendance.AttendanceRecords WHERE 1=1';
    const params = {};
    
    if (date) {
      query += ' AND Date = @date';
      params.date = date;
    }
    
    if (employeeId) {
      query += ' AND EmployeeId = @employeeId';
      params.employeeId = employeeId;
    }
    
    if (month) {
      query += ' AND Date LIKE @month';
      params.month = month + '%';
    }
    
    if (status) {
      query += ' AND Status = @status';
      params.status = status;
    }
    
    query += ' ORDER BY Date DESC, EmployeeId';
    
    const records = await execute(query, params);
    await Logger.info('READ', 'records', null, `Fetched ${records.length} records`, { filters: { date, employeeId, month, status } });
    res.json(records);
  } catch (error) {
    await Logger.error('READ', 'records', null, 'Failed to fetch records', { error: error.message });
    res.status(500).json({ error: 'Failed to fetch records' });
  }
});

// GET /api/records/:date/:employeeId - Get record by date and employee
router.get('/:date/:employeeId', async (req, res) => {
  try {
    const { date, employeeId } = req.params;
    // Decode the date parameter (it's URL-encoded on the frontend)
    const decodedDate = decodeURIComponent(date);
    
    console.log('🔍 Fetching record:', { date: decodedDate, employeeId });
    
    const records = await execute(
      'SELECT * FROM attendance.AttendanceRecords WHERE Date = @date AND EmployeeId = @employeeId',
      { date: decodedDate, employeeId }
    );
    
    console.log('📥 Found records:', records.length);
    
    if (records.length === 0) {
      return res.json(null);
    }
    res.json(records[0]);
  } catch (error) {
    console.error('❌ Error fetching record:', error);
    res.status(500).json({ error: 'Failed to fetch record' });
  }
});

// POST /api/records - Create new record
router.post('/', async (req, res) => {
  try {
    const { employeeId, date, clockIn, clockOut, status, note } = req.body;

    console.log('➕ Creating record:', { employeeId, date, clockIn, clockOut, status });

    // Id is INT IDENTITY — generated by the database (returned via SCOPE_IDENTITY()).
    const id = await executeInsert(`INSERT INTO attendance.AttendanceRecords (EmployeeId, Date, ClockIn, ClockOut, Status, Note)
       VALUES (@employeeId, @date, @clockIn, @clockOut, @status, @note)`, { employeeId, date, clockIn: clockIn || null, clockOut: clockOut || null, status, note: note || null });
    
    console.log('✅ Record created successfully');
    
    await Logger.success('CREATE', 'record', id, `Record created for employee ${employeeId}`, { 
      employeeId, date, clockIn, clockOut, status 
    });
    res.status(201).json({ message: 'Record created successfully' });
  } catch (error) {
    console.error('❌ Error creating record:', error);
    await Logger.error('CREATE', 'record', null, 'Failed to create record', { error: error.message, body: req.body });
    res.status(500).json({ error: 'Failed to create record', details: error.message });
  }
});

// PUT /api/records/:id - Update record
router.put('/:id', async (req, res) => {
  try {
    const { id } = req.params;
    const updates = req.body;
    
    console.log('🔄 Updating record:', { id, updates });
    
    // Build dynamic UPDATE query based on provided fields
    const setClauses = [];
    const params = { id };
    
    if (updates.clockIn !== undefined) {
      setClauses.push('ClockIn = @clockIn');
      params.clockIn = updates.clockIn || null;
    }
    
    if (updates.clockOut !== undefined) {
      setClauses.push('ClockOut = @clockOut');
      params.clockOut = updates.clockOut || null;
    }
    
    if (updates.status !== undefined) {
      setClauses.push('Status = @status');
      params.status = updates.status;
    }
    
    if (updates.note !== undefined) {
      setClauses.push('Note = @note');
      params.note = updates.note || null;
    }
    
    // Always update timestamp
    setClauses.push('UpdatedAt = GETDATE()');
    
    if (setClauses.length === 1) {
      // Only UpdatedAt, no actual changes
      return res.json({ message: 'No changes to update' });
    }
    
    const query = `UPDATE attendance.AttendanceRecords SET ${setClauses.join(', ')} WHERE Id = @id`;
    
    console.log('📝 Executing query:', query, params);
    
    await execute(query, params);
    
    console.log('✅ Record updated successfully');
    
    await Logger.success('UPDATE', 'record', id, `Record updated`, updates);
    res.json({ message: 'Record updated successfully' });
  } catch (error) {
    console.error('❌ Error updating record:', error);
    await Logger.error('UPDATE', 'record', req.params.id, 'Failed to update record', { error: error.message, body: req.body });
    res.status(500).json({ error: 'Failed to update record', details: error.message });
  }
});

// DELETE /api/records/:id - Delete record
router.delete('/:id', async (req, res) => {
  try {
    const { id } = req.params;
    await execute('DELETE FROM attendance.AttendanceRecords WHERE Id = @id', { id });
    await Logger.success('DELETE', 'record', id, 'Record deleted');
    res.json({ message: 'Record deleted successfully' });
  } catch (error) {
    await Logger.error('DELETE', 'record', req.params.id, 'Failed to delete record', { error: error.message });
    res.status(500).json({ error: 'Failed to delete record' });
  }
});

// GET /api/records/stats/weekly - Get weekly statistics
router.get('/stats/weekly', async (req, res) => {
  try {
    const { startDate, endDate } = req.query;
    const stats = await execute(
      `SELECT Date, 
               COUNT(CASE WHEN Status = 'present' THEN 1 END) AS PresentCount,
               COUNT(CASE WHEN Status = 'late' THEN 1 END) AS LateCount,
               COUNT(CASE WHEN Status = 'absent' THEN 1 END) AS AbsentCount
        FROM attendance.AttendanceRecords
        WHERE Date BETWEEN @startDate AND @endDate
        GROUP BY Date
        ORDER BY Date`,
      { startDate, endDate }
    );    res.json(stats);
  } catch (error) {
    console.error('Error fetching weekly stats:', error);
    res.status(500).json({ error: 'Failed to fetch weekly stats' });
  }
});

// GET /api/records/stats/monthly - Get monthly statistics
router.get('/stats/monthly', async (req, res) => {
  try {
    const { month } = req.query;
    const stats = await execute(
      `SELECT EmployeeId,
               COUNT(CASE WHEN Status = 'present' THEN 1 END) AS PresentDays,
               COUNT(CASE WHEN Status = 'late' THEN 1 END) AS LateDays,
               COUNT(*) AS TotalDays
        FROM attendance.AttendanceRecords
        WHERE Date LIKE @month
        GROUP BY EmployeeId`,
      { month: month + '%' }
    );    res.json(stats);
  } catch (error) {
    console.error('Error fetching monthly stats:', error);
    res.status(500).json({ error: 'Failed to fetch monthly stats' });
  }
});

export default router;
