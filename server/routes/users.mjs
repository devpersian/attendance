const router = Router();

// Phase 0 (route-auth enforcement): everything below requires a session token
// EXCEPT the legacy login endpoint, which is registered before the guard and
// delegates to the same credential flow as /api/auth/login (see P0.2).
router.post('/login', rateLimit({ windowMs: 15 * 60_000, max: 20 }), async (req, res) => {
  // Phase 1 / P1.1: single shared credential flow (lockout + audit + expiry)
  try {
    const { username, password } = req.body || {};
    if (!username || !password) {
      return res.status(400).json({ error: 'نام کاربری و رمز عبور الزامی است' });
    }
    const result = await performLogin({ username, password, req });
    return res.status(result.status).json(result.body);
  } catch (error) {
    await Logger.error('LOGIN', 'user', null, 'خطا در ورود', { error: error.message });
    res.status(500).json({ error: 'خطا در ورود' });
  }
});

router.use(authenticateToken);

// Admin-only mutation guard for user management endpoints. The seeded admin
// account carries Users.Role='admin'; additionally accept holders of the
// users module root permission via the role tree (requirePermission handles it).
async function requireUserAdmin(req, res, next) {
  try {
    if (await hasEffectivePermission(req.user, 'users')) return next();
  } catch (error) {
    return res.status(500).json({ error: 'خطا در بررسی دسترسی' });
  }
  return res.status(403).json({ error: 'شما دسترسی به این بخش را ندارید' });
}

// Register (admin only)
router.post('/register', requireUserAdmin, async (req, res) => {
  try {
    const { username, password, email, role, employeeId } = req.body;

    if (!username || !password) {
      return res.status(400).json({ error: 'نام کاربری و رمز عبور الزامی است' });
    }

    // Check if username exists
    const existing = await execute('SELECT Id FROM attendance.Users WHERE Username = @username', { username });

    if (existing.length > 0) {
      return res.status(400).json({ error: 'این نام کاربری قبلاً استفاده شده است' });
    }

    // Phase 1 / P1.2: central password policy on creation
    const policy = validatePassword(password);
    if (!policy.ok) {
      return res.status(400).json({ error: policy.errors.join(' — ') });
    }

    // Hash password
    const passwordHash = await bcrypt.hash(password, 10);

    // Id is INT IDENTITY — generated by the database
    const userId = await executeInsert(    `INSERT INTO attendance.Users (Username, PasswordHash, Email, Role, EmployeeId, IsActive)
       VALUES (@username, @passwordHash, @email, @role, @employeeId, 1)`, { username, passwordHash, email, role: role || 'employee', employeeId });

    await recordPasswordHash(userId, passwordHash); // initial hash enters history (P1.3)
    await writeAudit({ actorUserId: req.user.id, action: 'USER_CREATED', entity: 'user', entityId: userId, detail: { username, role: role || 'employee' }, req });
    await Logger.info('REGISTER', 'user', userId, 'کاربر جدید ثبت شد', { userId, username, role });

    res.status(201).json({ message: 'کاربر با موفقیت ثبت شد', userId });
  } catch (error) {
    await Logger.error('REGISTER', 'user', null, 'خطا در ثبت کاربر', { error: error.message });
    res.status(500).json({ error: 'خطا در ثبت کاربر' });
  }
});

// Get all users (admin/users-managers only)
